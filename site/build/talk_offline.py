#!/usr/bin/env python3
"""Build the offline talk files: the player with the timeline, its data and its images inlined, so it opens from a
file with no server and no network (the version to carry into a room with bad wifi).
Usage: python3 site/build/talk_offline.py   ->  site/talk/offline-10.html, site/talk/offline-5.html"""
import base64, json, pathlib
TALK = pathlib.Path(__file__).resolve().parents[1] / 'talk'
player = (TALK / 'player.html').read_text(encoding='utf-8')
MARK = '<script>\n// Talk player'
assert MARK in player, 'player.html changed shape: update talk_offline.py'
for n in ('10', '5'):
    talk = json.loads((TALK / f'talk-{n}.json').read_text(encoding='utf-8'))
    data = {k: json.loads((TALK / p).read_text(encoding='utf-8')) for k, p in talk.get('data', {}).items()}
    images = {}
    for b in talk['beats']:
        for key in ('src', 'fallback'):
            src = b['slide'].get(key, '')
            if b['slide']['layout'] in ('image', 'iframe') and src.endswith(('.webp', '.png', '.jpg')):
                mime = 'image/' + ('jpeg' if src.endswith('.jpg') else src.rsplit('.', 1)[1])
                images[src] = f'data:{mime};base64,' + base64.b64encode((TALK / src).read_bytes()).decode()
    js = lambda v: json.dumps(v, ensure_ascii=False).replace('</', '<\\/')   # no '</script>' inside the inline script
    inline = ''.join(f'window.{k} = {js(v)};\n' for k, v in (('TALK', talk), ('TALK_DATA', data), ('TALK_IMAGES', images)))
    out = player.replace(MARK, f'<script>\n// generated by site/build/talk_offline.py from talk-{n}.json: do not edit\n{inline}</script>\n{MARK}', 1)
    (TALK / f'offline-{n}.html').write_text(out, encoding='utf-8')
    print(f'talk/offline-{n}.html', len(out) // 1024, 'KB,', len(talk['beats']), 'beats,', len(images), 'images inlined')
